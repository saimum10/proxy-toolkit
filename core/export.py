"""Export helpers. All functions take a list of ProxyResult in the order to be written."""
from __future__ import annotations

import csv
import ipaddress
import json
import re
import time
from collections import defaultdict
from pathlib import Path

from .models import fmt_host

CSV_FIELDS = ["proxy", "url", "type", "live", "exit_ip", "country", "country_code", "city",
              "anonymity", "remote_dns", "latency_ms", "stability", "score", "targets",
              "network", "isp", "error"]


def _row(r) -> dict:
    return {
        "proxy": r.address,
        "url": r.url,
        "type": r.proto,
        "live": r.live,
        "exit_ip": r.exit_ip,
        "country": r.country,
        "country_code": r.country_code,
        "city": r.city,
        "anonymity": r.anonymity,
        "remote_dns": r.remote_dns,
        "latency_ms": round(r.latency_ms) if r.latency_ms is not None else None,
        "stability": f"{r.passed}/{r.rounds}" if r.rounds else "",
        "score": r.score if r.live else None,
        "targets": r.targets,
        "network": r.net_type,
        "isp": r.isp,
        "error": r.error,
    }


def export_json(results, path) -> int:
    rows = [_row(r) for r in results]
    Path(path).write_text(json.dumps(rows, indent=2, ensure_ascii=False), encoding="utf-8")
    return len(rows)


def export_csv(results, path) -> int:
    n = 0
    with open(path, "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=CSV_FIELDS)
        w.writeheader()
        for r in results:
            row = _row(r)
            row["targets"] = " ".join(f"{k}:{'ok' if v else 'fail'}" for k, v in r.targets.items())
            w.writerow(row)
            n += 1
    return n


def export_txt(results, path) -> int:
    """One working proxy URL per line (live only)."""
    urls = [r.url for r in results if r.live]
    Path(path).write_text("\n".join(urls) + ("\n" if urls else ""), encoding="utf-8")
    return len(urls)


def export_by_country(results, folder) -> int:
    """Write <CC>.txt per country (live only) plus all_live.txt. Returns number of files."""
    folder = Path(folder)
    folder.mkdir(parents=True, exist_ok=True)
    groups = defaultdict(list)
    for r in results:
        if r.live:
            cc = re.sub(r"[^A-Za-z0-9]", "", r.country_code) or "unknown"
            groups[cc.upper()].append(r.url)
    for cc, urls in groups.items():
        (folder / f"{cc}.txt").write_text("\n".join(urls) + "\n", encoding="utf-8")
    all_urls = [u for urls in groups.values() for u in urls]
    (folder / "all_live.txt").write_text("\n".join(all_urls) + ("\n" if all_urls else ""),
                                          encoding="utf-8")
    return len(groups) + 1


# ------------------------------------------------------------------ proxychains / PAC

PROXYCHAINS_TYPES = [
    ("dynamic_chain", "dynamic_chain - chain ALL proxies in order, skip dead ones"),
    ("strict_chain", "strict_chain - chain ALL proxies in order, fail if one is dead"),
    ("random_chain", "random_chain - pick random proxies per connection (rotation)"),
]


def _pc_line(r):
    """One [ProxyList] line, or None when proxychains cannot express this proxy.

    proxychains(-ng) only knows http / socks4 / socks5, wants literal IPv4 addresses and
    whitespace separated fields (so credentials with spaces are impossible)."""
    if r.link or r.proto not in ("http", "socks4", "socks5"):
        return None                    # (links live on a local engine port, not on a real proxy)
    try:
        ipaddress.IPv4Address(r.host)
    except ValueError:
        return None
    user, pw = r.user or "", r.password or ""
    if re.search(r"\s", user + pw):
        return None
    if r.proto == "socks4":
        if user:                       # proxychains' socks4 type has no credentials field we can rely on
            return None
        return f"socks4 {r.host} {r.port}"
    line = f"{r.proto} {r.host} {r.port}"
    if user:
        line += f" {user} {pw}".rstrip() if pw else f" {user}"
    return line


def proxychains_text(lines: list, chain: str = "dynamic_chain", chain_len: int = 1,
                     proxy_dns: bool = True, comment: str = "") -> str:
    head = ["# proxychains configuration generated by Proxy Toolkit "
            + time.strftime("%Y-%m-%d %H:%M"), ]
    if comment:
        head.append("# " + comment)
    head.append("# usage:  proxychains4 -f <this file> curl https://api.ipify.org")
    head.append("")
    head.append(chain)
    if chain == "random_chain":
        head.append(f"chain_len = {max(1, chain_len)}")
    if proxy_dns:
        head.append("proxy_dns")
    head += ["tcp_read_time_out 15000", "tcp_connect_time_out 8000", "", "[ProxyList]"]
    return "\n".join(head + lines) + "\n"


def export_proxychains(results, path, chain: str = "dynamic_chain", chain_len: int = 1,
                       proxy_dns: bool = True):
    """Write a proxychains.conf from the live proxies. Returns (written, skipped)."""
    if chain not in dict(PROXYCHAINS_TYPES):
        raise ValueError(f"unknown chain type {chain!r}")
    lines, skipped = [], 0
    for r in results:
        if not r.live:
            continue
        line = _pc_line(r)
        if line is None:
            skipped += 1
        else:
            lines.append(line)
    Path(path).write_text(proxychains_text(lines, chain, chain_len, proxy_dns), encoding="utf-8")
    return len(lines), skipped


def export_proxychains_local(path, host: str, port: int, chain: str = "strict_chain") -> int:
    """proxychains.conf that sends everything through the running Proxy Toolkit server."""
    if host in ("", "0.0.0.0", "::"):
        host = "127.0.0.1"
    Path(path).write_text(
        proxychains_text([f"socks5 {host} {port}"], chain, 1, True,
                         "all traffic goes through the local Proxy Toolkit server"),
        encoding="utf-8")
    return 1


_PAC_MAP = {"http": "PROXY", "https": "HTTPS", "socks4": "SOCKS4", "socks5": "SOCKS5"}


def pac_text(servers: list, bypass_local: bool = True, comment: str = "") -> str:
    """PAC file returning `servers` (e.g. ["SOCKS5 1.2.3.4:1080", ...]) as a fail-over list.

    There is deliberately NO "DIRECT" fallback: when every proxy is down the browser shows an
    error instead of silently connecting from your real IP. Local addresses are matched on the
    literal host name only - never with dnsResolve() - so the PAC itself cannot leak DNS."""
    ret = "; ".join(servers)
    out = [f"// PAC file generated by Proxy Toolkit {time.strftime('%Y-%m-%d %H:%M')}"]
    if comment:
        out.append(f"// {comment}")
    out += ["function FindProxyForURL(url, host) {"]
    if bypass_local:
        out += [
            "  // loopback / private networks / plain host names are not proxied",
            "  if (isPlainHostName(host) || host === \"localhost\" || host === \"[::1]\" ||",
            "      /^(127\\.|10\\.|192\\.168\\.|169\\.254\\.|172\\.(1[6-9]|2[0-9]|3[01])\\.)/.test(host) ||",
            "      /\\.local$/.test(host)) {",
            "    return \"DIRECT\";",
            "  }",
        ]
    out += [f"  return {json.dumps(ret)};", "}", ""]
    return "\n".join(out)


def export_pac(results, path, limit: int = 10, bypass_local: bool = True):
    """PAC file with the best live proxies as fail-over list. Returns (written, skipped).

    Browsers cannot send proxy credentials from a PAC file, so proxies that need a
    username / password are skipped."""
    live = sorted((r for r in results if r.live),
                  key=lambda r: (-r.score, r.latency_ms if r.latency_ms is not None else 1e12))
    servers, skipped = [], 0
    for r in live:
        if r.link or r.user or r.proto not in _PAC_MAP:
            skipped += 1
            continue
        if len(servers) < max(1, limit):
            servers.append(f"{_PAC_MAP[r.proto]} {fmt_host(r.host)}:{r.port}")
    Path(path).write_text(
        pac_text(servers, bypass_local, f"best {len(servers)} live proxies, tried in this order"),
        encoding="utf-8")
    return len(servers), skipped


def export_pac_local(path, host: str, port: int, bypass_local: bool = True) -> int:
    """PAC file that sends the browser through the running Proxy Toolkit server."""
    if host in ("", "0.0.0.0", "::"):
        host = "127.0.0.1"
    hp = f"{fmt_host(host)}:{port}"
    Path(path).write_text(
        pac_text([f"SOCKS5 {hp}", f"PROXY {hp}"], bypass_local,
                 "local Proxy Toolkit server (SOCKS5, HTTP fall-back on the same port)"),
        encoding="utf-8")
    return 1
